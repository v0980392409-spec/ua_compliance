// Список «Класифікатори» за контрактом екранів (екран 9). Два класифікатори лежать в одній
// таблиці й сортуються за кодом, тож КВЕД («01», «01.1»…) заступав КАТОТТГ («UA…») на
// перших сторінках (демо 04.10.2026). Швидкий фільтр «Класифікатор» платформа будує сама
// з ознаки in_standard_filter поля; тут лишається прибрати перед ним технічний
// ідентифікатор «{класифікатор}-{код}» — і з рядка фільтрів, і з колонок.

frappe.listview_settings["UA Classifier Entry"] = {
	hide_name_filter: true,
	hide_name_column: true,

	// Виведений код лишається в списку (FR-049), але позначений сірим (контракт, екран 9);
	// чинний код індикатора не має — на 32 000 рядків зелена позначка була б лише шумом.
	get_indicator(doc) {
		const today = frappe.datetime.get_today();
		if (doc.valid_to && doc.valid_to < today) {
			return [__("Закрито"), "gray", `valid_to,<,${today}`];
		}
	},
};
